"""Walk through stetiq on the retail-orders Knowledge Graph: the operations side.

    cd examples/retail-orders-kg
    uv run python demo.py            # a few seconds, fully offline
    uv run stetiq ui                 # then browse the result

A large graph (about 13,000 nodes at season start, generated by retail_synth.py), six
Construction Runs compared side by side, and a season of eight weekly Observations with
statistical and structural Drift. Everything is local: the tracking database is
.stetiq/stetiq.db, the graph database is an in-memory stand-in (retail_graph.py) that
lives only while the demo runs. README.md tells the story.
"""

from __future__ import annotations

import argparse
import datetime as dt
import random
import sys
from collections import Counter
from pathlib import Path

EXAMPLE_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(EXAMPLE_DIR))

from retail_graph import LOADERS_ALL, LOADERS_ORDERS, SCOPE, BuildParams, RetailGraph  # noqa: E402
from retail_synth import (  # noqa: E402
    EXACT_DUPLICATES,
    GUEST_CHECKOUTS,
    SEED,
    Week,
    generate_batch,
    generate_season_start,
    load_seeds,
)

import stetiq  # noqa: E402
from stetiq.config import load_config  # noqa: E402
from stetiq.drift import thresholds_from_config  # noqa: E402

KG = "retail-orders"
CONFIG = EXAMPLE_DIR / "stetiq.yaml"
ONTOLOGY = EXAMPLE_DIR / "ontology"
USE_CASE = EXAMPLE_DIR / "use-case.yaml"
DEFAULT_TRACKING_URI = f"sqlite:///{EXAMPLE_DIR / '.stetiq' / 'stetiq.db'}"

DESCRIPTION = """The order graph of an online retailer: **customers**, **orders** and their
**lines**, the **product** catalogue with its three-level **category** tree, **suppliers**,
**warehouses**, **shipments** and (from v3) **returns**.

Built by the pipeline in `examples/retail-orders-kg/retail_graph.py` from synthetic data;
the Competency Questions are the analytics team's questions in `use-case.yaml`."""

# The six Construction Runs of Act 2: the pipeline's params, and what each run is for.
RUNS: tuple[tuple[BuildParams, str], ...] = (
    (BuildParams("none", 500, LOADERS_ORDERS, False), "smoke run: catalogue and orders only"),
    (BuildParams("none", 1000, LOADERS_ALL, False), "every loader, duplicate customers kept"),
    (BuildParams("exact", 1000, LOADERS_ALL, False), "exact-email dedupe"),
    (BuildParams("fuzzy", 2000, LOADERS_ALL, False), "fuzzy dedupe merges the guest checkouts"),
    (BuildParams("fuzzy", 2000, LOADERS_ALL, True), "returns switched on: Return and RETURNED"),
    (BuildParams("fuzzy", 2000, LOADERS_ALL, True), "the same pipeline, consuming v3"),
)
NIGHTLY = BuildParams("fuzzy", 2000, LOADERS_ALL, True)  # what the season's nightly runs use


def build_seconds(params: BuildParams) -> float:
    """The pipeline's own timing, logged as a metric. Synthetic, so the demo is deterministic."""
    seconds = {500: 71.4, 1000: 44.9, 2000: 31.2}[params.batch_size]
    seconds += 6.5 if "shipments" in params.loaders else 0.0
    return round(seconds + (3.8 if params.include_returns else 0.0), 1)


class Demo:
    """The state the walkthrough builds up (the test reads it back)."""

    def __init__(self, *, tracking_uri: str, quiet: bool) -> None:
        self.tracking_uri = tracking_uri
        self.quiet = quiet
        self.seeds = load_seeds()
        self.season = generate_season_start(self.seeds)
        self.graph = RetailGraph(self.seeds, USE_CASE)
        # Two users of the same tracking database: the data engineer who builds and the CI
        # job that gates and promotes. The audit log names each one.
        self.mara = stetiq.Client(tracking_uri, graph_source=self.graph, actor="mara.lindqvist")
        self.ci = stetiq.Client(tracking_uri, graph_source=self.graph, actor="ci-bot")
        self.thresholds = thresholds_from_config(load_config(CONFIG))
        self.runs: list[stetiq.ConstructionRun] = []
        self.weeks: dict[int, stetiq.ObservationOutcome] = {}

    # --- output -------------------------------------------------------------------------

    def say(self, *lines: str) -> None:
        if not self.quiet:
            print(*lines, sep="\n", flush=True)

    def act(self, title: str) -> None:
        self.say("", f"=== {title} ", "")

    # --- 1. declare ---------------------------------------------------------------------

    def declare(self) -> None:
        self.act("1. Declare: the Knowledge Graph, its label-scoped Graph Source, its Use Case")
        client = self.mara
        client.create_knowledge_graph(KG, ontology=ONTOLOGY / "v1.yaml")
        client.set_knowledge_graph_description(KG, DESCRIPTION)
        client.bind_graph_source(KG, SCOPE)
        v1 = client.get_ontology_version(KG, 1).ontology
        self.say(
            f"Created {KG} from ontology/v1.yaml: Ontology Version 1 with "
            f"{len(v1.node_types)} node types and {len(v1.relationship_types)} relationship "
            f"types (Department is a child of Category); production -> v1",
            f"Bound the Graph Source scope database={SCOPE.database} label={SCOPE.label}: "
            "only nodes carrying the Retail label are ever observed",
        )
        use_case = client.register_use_case(KG, USE_CASE)
        self.say(
            f"Registered the Use Case (Use Case Version {use_case.number}): "
            f"{len(use_case.use_case.competency_questions)} Competency Questions"
        )
        self.show_answerability(1)

    def show_answerability(self, version: int) -> None:
        result = _result(self.mara.get_evaluation_results(KG, version), "structural_answerability")
        m = result.metrics
        self.say(
            f"structural_answerability of v{version}: {m['answerable_questions']}/{m['questions']} "
            f"answerable, {m['unanswerable_questions']} unanswerable, "
            f"{m['unmapped_questions']} unmapped (ratio {m['answerable_ratio']:.3f})"
        )
        for d in result.details:
            if d.data and d.data["status"] != "answerable":
                self.say(f"  - {d.item}: {d.message}")

    # --- 2. build -----------------------------------------------------------------------

    def build(self) -> None:
        self.act("2. Build: six Construction Runs of the pipeline, compared")
        for params, note in RUNS[:5]:
            self.construction_run(params, note)
        self.adopt_candidate()
        params, note = RUNS[5]
        self.construction_run(params, note, ontology_version=self.v3.number)
        self.compare()

    def construction_run(
        self, params: BuildParams, note: str, *, ontology_version: int | None = None
    ) -> stetiq.ConstructionRun:
        with self.mara.start_run(KG, ontology_version=ontology_version) as run:
            run.log_params(params.as_params())
            stats = self.graph.rebuild(self.season.records, self.season.batch, params)
            run.log_metrics(
                {
                    "customers": stats.customers,
                    "duplicate_customers_merged": stats.duplicate_customers_merged,
                    "orders": stats.orders,
                    "order_lines": stats.order_lines,
                    "build_seconds": build_seconds(params),
                }
            )
        finished = self.mara.get_run(run.id)
        self.runs.append(finished)
        self.say(
            f"Run {len(self.runs)} ({finished.id[:8]}, {note}) declared v{finished.ontology_version}: "
            f"{stats.customers} customers ({stats.duplicate_customers_merged} rows merged), "
            f"{stats.orders} orders, {stats.order_lines} lines, {stats.shipments} shipments, "
            f"{stats.returns} returns"
        )
        self.show_run(finished)
        return finished

    def show_run(self, run: stetiq.ConstructionRun) -> None:
        mismatches = run.conformance.mismatches
        self.say(
            f"  status {run.status}; Conformance {run.conformance.score:.3f}"
            + (f" with {len(mismatches)} mismatches:" if mismatches else "")
        )
        for m in mismatches[:6]:
            self.say(f"    - {m.kind} {m.subject_kind} {m.subject}")
        if run.candidate_version:
            self.say(
                f"  evolving mode registered Candidate Ontology Version {run.candidate_version}"
            )
        results = self.mara.get_run_evaluation_results(run.id)
        execution = _result(results, "competency_question_execution")
        schema = _result(results, "observed_schema").metrics
        failed = [d.item for d in execution.details if d.data and d.data["status"] != "passed"]
        m = execution.metrics
        self.say(
            f"  executed Competency Questions: {m['passed_questions']}/{m['questions']} passed"
            + (f" (failed: {', '.join(failed)})" if failed else ""),
            f"  observed_schema: {schema['nodes']:.0f} nodes, {schema['relationships']:.0f} "
            f"relationships, mean_fill_rate {schema['mean_fill_rate']:.3f}",
        )

    def adopt_candidate(self) -> None:
        self.candidate = self.mara.latest_candidate(KG)
        diff = self.mara.diff_ontology_versions(KG)  # contract (v1) -> latest Candidate
        self.say(
            "",
            f"latest_candidate: v{self.candidate.number} (origin {self.candidate.origin}); "
            f"Ontology Diff v1 -> v{self.candidate.number} is {diff.classification}:",
        )
        for c in diff.changes:
            self.say(f"  - {c.classification} {c.kind} {c.concept_kind} {c.concept}: {c.detail}")
        self.v3 = self.mara.register_ontology(KG, ONTOLOGY / "v3.yaml")
        descriptions = self.mara.diff_ontology_versions(KG, self.candidate.number, self.v3.number)
        self.say(
            f"Mara adopts it as ontology/v3.yaml with descriptions: registered as v{self.v3.number} "
            f"(origin {self.v3.origin}), a new version and not a dedupe hit, because the content "
            f"differs from v{self.candidate.number} by {len(descriptions.changes)} description changes",
            "",
        )

    def compare(self) -> None:
        self.comparison = self.mara.compare_runs([r.id for r in self.runs])
        cmp = self.comparison
        self.say("", "compare_runs over the six runs (columns: run 1 .. run 6)")
        rows: list[tuple[str, tuple[object, ...]]] = [
            ("ontology_version", tuple(f"v{n}" for n in cmp.ontology_versions)),
            *((f"param {k}", v) for k, v in cmp.params.items()),
            *((f"metric {k}", v) for k, v in cmp.metrics.items()),
            ("Conformance", tuple(c.score if c else None for c in cmp.conformance)),
            *(
                (k, v)
                for k, v in cmp.evaluations.items()
                if k in ("competency_question_execution.pass_ratio", "observed_schema.nodes")
            ),
        ]
        width = max(len(name) for name, _ in rows)
        columns = [
            max(len(_cell(v)) for _, values in rows for v in [values[i]])
            for i in range(len(self.runs))
        ]
        for name, values in rows:
            cells = (f"{_cell(v):>{w}}" for v, w in zip(values, columns, strict=True))
            self.say(f"  {name:<{width}}  " + "  ".join(cells))
        best = max(c.score for c in cmp.conformance if c)
        best_runs = [i + 1 for i, c in enumerate(cmp.conformance) if c and c.score == best]
        self.say(f"  Best Conformance {best:.3f}: run(s) {', '.join(map(str, best_runs))}")
        merged = self.runs[3].metrics["duplicate_customers_merged"]
        self.say(
            f"  Note the fuzzy runs merged {merged:.0f} rows for {EXACT_DUPLICATES + GUEST_CHECKOUTS} "
            f"real duplicates: {merged - EXACT_DUPLICATES - GUEST_CHECKOUTS:.0f} different people "
            "share a name and a postcode. Conformance is about structure and cannot see that."
        )

    # --- 3. gate and promote -------------------------------------------------------------

    def gate_and_promote(self) -> None:
        self.act("3. Gate: the Gates of stetiq.yaml on v3, then Promotion")
        self.gates_v3 = self.ci.evaluate_gates(KG, CONFIG, version=self.v3.number)
        self.show_gates(self.gates_v3)
        if self.gates_v3.passed:
            self.mara.set_alias(KG, "staging", self.v3.number)
            self.ci.set_alias(KG, "production", self.v3.number)
            self.say(
                f"Promoted: staging -> v{self.v3.number} (mara), production -> v{self.v3.number} (ci-bot)"
            )
        else:
            self.say("Gates failed: not promoting.")

    def show_gates(self, result: stetiq.GateResult) -> None:
        subject = (
            f"Construction Run {result.subject_id[:8]}"
            if result.subject_kind == "construction_run"
            else f"Ontology Version {result.ontology_version}"
        )
        self.say(
            f"Gates on {subject}: "
            f"{'all passed' if result.passed else f'{len(result.failed)} of {len(result.outcomes)} failed'}"
        )
        for o in result.outcomes:
            self.say(f"  {'PASS' if o.passed else 'FAIL'}  {o.gate.name}")
            for reason in o.reasons[: 3 if o.passed else 4]:
                self.say(f"        - {reason}")

    # --- 4. operate ----------------------------------------------------------------------

    def operate(self) -> None:
        self.act("4. Operate: eight weekly Observations over the autumn season")
        self.mara.set_evolution_mode(KG, "strict")
        self.say(
            "Evolution Mode strict for the season: a nightly run that meets new Concepts fails "
            "instead of registering a Candidate",
            f"Drift thresholds from stetiq.yaml: max_count_drop={self.thresholds.max_count_drop}, "
            f"max_count_increase={self.thresholds.max_count_increase}",
        )
        self.rng = random.Random(SEED + 1)
        for week in self.seeds.weeks:
            self.week(week)

    def week(self, week: Week) -> None:
        self.say("", f"Week {week.number} ({week.observed_on})")
        if week.orders_factor:
            added = self.grow(week)
            self.say(
                f"  +{added} orders this week ({week.orders_factor:+.0%} of the Orders in the graph)"
            )
        if "flash_sale" in week.events:
            self.say("  Flash sale: more than twice the usual orders, half not shipped yet")
        if "bin_migration" in week.events:
            bins, stored = self.graph.add_bins(self.rng)
            self.say(f"  The warehouse team's migration adds {bins} Bin nodes, {stored} STORED_IN")
        if "shipment_retention" in week.events:
            deleted = self.graph.purge_shipments(self.rng, week.retention_passes[0])
            self.say(f"  The retention job's first batch deletes {deleted} Shipment nodes")
        if "ontology_v4" in week.events:
            self.declare_v4()
        self.weeks[week.number] = outcome = self.mara.observe(KG, thresholds=self.thresholds)
        self.show_observation(outcome)
        if "shipment_retention" in week.events:
            deleted = self.graph.purge_shipments(self.rng, week.retention_passes[1])
            self.say(
                f"  The second batch deletes {deleted} more Shipment nodes before the nightly run"
            )
            self.week6_run = self.nightly_run()
            self.gates_week6 = self.ci.evaluate_gates(KG, CONFIG, run=self.week6_run.id)
            self.show_gates(self.gates_week6)

    def grow(self, week: Week) -> int:
        orders = round(week.orders_factor * self.graph.count("Order"))
        observed_on = dt.date.fromisoformat(week.observed_on)
        batch = generate_batch(
            self.rng,
            self.season.sequence,
            self.seeds,
            self.graph.customer_keys(),
            orders=orders,
            first_day=observed_on - dt.timedelta(days=6),
            shipped_share=week.shipped_share,
            return_share=week.return_share,
        )
        self.graph.add_batch(batch)
        return orders

    def show_observation(self, outcome: stetiq.ObservationOutcome) -> None:
        schema = outcome.observation.schema
        nodes = sum(t.count for t in schema.node_types)
        relationships = sum(t.count for t in schema.relationship_types)
        self.say(
            f"  Observation {outcome.observation.id[:8]}: {len(schema.node_types)} node types "
            f"({nodes} nodes), {len(schema.relationship_types)} relationship types "
            f"({relationships} relationships)"
        )
        if outcome.drift is None:
            self.say("  No Drift")
            return
        d = outcome.drift
        self.say(
            f"  DRIFT against {d.contract_alias} -> v{d.ontology_version}: "
            f"{len(d.structural)} structural, {len(d.statistical)} statistical finding(s)"
        )
        for f in d.findings:
            self.say(
                f"    - {f.kind} {f.subject_kind} {f.subject}"
                + (f": {f.detail}" if f.detail else "")
            )

    def nightly_run(self, *, ontology_version: int | None = None) -> stetiq.ConstructionRun:
        """The nightly rebuild, as `stetiq run` would start it: the whole scope again from
        the feed plus the season's batches so far, under the Contract Alias's version
        unless the run is pointed at another one (`stetiq run --ontology-version`)."""
        with self.mara.start_run(KG, ontology_version=ontology_version) as run:
            run.log_params({**NIGHTLY.as_params(), "schedule": "nightly"})
            # The pipeline rebuilds from the feed; here the graph already holds that state,
            # so the run only observes what the week left behind.
            run.log_metrics(
                {"orders": self.graph.count("Order"), "build_seconds": build_seconds(NIGHTLY)}
            )
        finished = self.mara.get_run(run.id)
        undeclared = sorted(
            m.subject
            for m in finished.conformance.mismatches
            if str(m.kind) == "undeclared" and m.subject_kind != "pattern"
        )
        self.say(
            f"  Nightly Construction Run {finished.id[:8]} under v{finished.ontology_version}: "
            f"status {finished.status}, Conformance {finished.conformance.score:.3f}"
        )
        if undeclared:
            self.say(f"    strict mode failed it over undeclared Concepts: {', '.join(undeclared)}")
        return finished

    def declare_v4(self) -> None:
        self.v4 = self.mara.register_ontology(KG, ONTOLOGY / "v4.yaml")
        diff = self.mara.diff_ontology_versions(KG, self.v3.number, self.v4.number)
        self.say(
            f"  The team registers ontology/v4.yaml as v{self.v4.number}: diff v{self.v3.number} -> "
            f"v{self.v4.number} is {diff.classification} ({len(diff.changes)} changes: "
            + ", ".join(c.concept for c in diff.changes if c.kind == "added")
            + ")"
        )
        # Pointed at v4 before anything is promoted: the Gates need a run standing for v4.
        self.week7_run = self.nightly_run(ontology_version=self.v4.number)
        self.gates_v4 = self.ci.evaluate_gates(KG, CONFIG, version=self.v4.number)
        self.show_gates(self.gates_v4)
        if self.gates_v4.passed:
            self.ci.set_alias(KG, "production", self.v4.number)
            self.say(f"  Promoted: production -> v{self.v4.number} (ci-bot)")

    # --- 5. finish -----------------------------------------------------------------------

    def finish(self) -> None:
        self.act("5. The season in review")
        versions = self.mara.list_ontology_versions(KG)
        self.say(
            f"{KG}: Ontology Versions "
            + ", ".join(f"v{v.number} ({v.origin})" for v in versions)
            + f"; production -> v{self.mara.get_contract_version(KG).number}"
        )
        events = self.mara.list_drift_events(KG)
        self.say(f"Drift events: {len(events)}")
        for e in events:
            kinds = Counter(str(f.kind) for f in e.findings)
            self.say(
                f"  - against v{e.ontology_version}: "
                + ", ".join(f"{k} x{n}" for k, n in sorted(kinds.items()))
            )
        last = self.weeks[max(self.weeks)].observation.schema
        nodes = sum(t.count for t in last.node_types)
        relationships = sum(t.count for t in last.relationship_types)
        self.say(
            "",
            "Cost of doing this at scale: an Observation sends aggregates only. The last one "
            f"describes {nodes} nodes and {relationships} relationships as {len(last.node_types)} "
            f"node types, {len(last.relationship_types)} relationship types and {len(last.patterns)} "
            f"patterns; the Graph Source was read {self.graph.observations} times, and the "
            "tracking database holds no customer, order or product.",
        )
        here = EXAMPLE_DIR.resolve() == Path.cwd().resolve()
        self.say(
            "",
            "The CLI on this tracking database" + ("" if here else f" (from {EXAMPLE_DIR})") + ":",
            "  uv run stetiq ui                      # http://127.0.0.1:5000/ui",
            f"  uv run stetiq runs compare {' '.join(r.id for r in self.runs[:2])} ...",
            f"  uv run stetiq gate {KG} --run {self.week6_run.id}   # 3 of 7 fail now: the diff is v4 -> v3",
            f"  uv run stetiq drift list {KG}",
            f"  uv run stetiq ontology diff {KG} 1 4",
            f"  uv run stetiq alias log {KG}",
        )


def _result(results: list[stetiq.EvaluationResult], evaluator: str) -> stetiq.EvaluationResult:
    return next(r for r in results if r.evaluator == evaluator)


def _cell(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.3f}" if value != int(value) else f"{value:.0f}"
    return str(value)


def run_demo(*, tracking_uri: str = DEFAULT_TRACKING_URI, quiet: bool = False) -> Demo:
    demo = Demo(tracking_uri=tracking_uri, quiet=quiet)
    demo.say(f"stetiq {demo.tracking_uri}; Graph Source: in-memory, scope {SCOPE}")
    demo.declare()
    demo.build()
    demo.gate_and_promote()
    demo.operate()
    demo.finish()
    return demo


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--tracking-uri", default=DEFAULT_TRACKING_URI)
    parser.add_argument("--reset", action="store_true", help="delete the tracking database first")
    args = parser.parse_args(argv)

    db = (
        Path(args.tracking_uri.removeprefix("sqlite:///"))
        if args.tracking_uri.startswith("sqlite:///")
        else None
    )
    if args.reset:
        if db is not None and db.exists():
            db.unlink()
    elif db is not None and db.exists():
        print(
            f"{db} already holds a previous walkthrough; pass --reset to start over",
            file=sys.stderr,
        )
        return 1
    if db is not None:
        db.parent.mkdir(parents=True, exist_ok=True)
    try:
        run_demo(tracking_uri=args.tracking_uri)
    except stetiq.StetiqError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
